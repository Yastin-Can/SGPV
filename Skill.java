public class Skill {
    private String name;
    private int level; // 1 - 5 (1 nivel bajo - 5 nivel alto)

    public String getName() {
        return name;
    }

    public int getLevel() {
        return level;
    }

    public void setName(String name) {
        this.name = name;
    }

    public void setLevel(int level) {
        this.level = level;
    }

}
